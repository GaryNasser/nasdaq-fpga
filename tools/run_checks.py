env = dict(os.environ)
env["PATH"] = r"D:\Xilinx\Vivado\2024.1\bin;" + env.get("PATH", "")
env["PYTHONIOENCODING"] = "utf-8"
have_vivado = os.path.exists(r"D:\Xilinx\Vivado\2024.1\bin\xvlog.bat")

results = []
print("=" * 74)
print("static contract suite")
print("=" * 74)

for key, desc, needs_vivado in CHECKS:
    path = os.path.join(TOOLS, SCRIPT[key])
    if needs_vivado and not have_vivado:
        print("[SKIP] %-16s %s" % (key, desc))
        results.append((key, "SKIP", desc))
        continue
    # Decode explicitly as UTF-8. text=True alone uses the locale codec (GBK here),
    # which raises on the UTF-8 the checkers print and loses their diagnostic exactly
    # when a check fails.
    r = subprocess.run([sys.executable, path], cwd=TOOLS,
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", env=env)
    out = (r.stdout or "") + (r.stderr or "")
    ok = (r.returncode == 0)
    # Find the verdict token each checker prints.
    verdict = ""
    for line in reversed(out.strip().splitlines()):
        s = line.strip()
        if "PASS" in s or "FAIL" in s or "OK" in s:
            verdict = s
            break
    # Exit 75 is the PENDING convention: the check found a gap that the hardware
    # supports and that only board access stands in the way of. Reported on
    # every run, counted as neither a pass nor a failure.
    if r.returncode == 75:
        status = "PEND"
    else:
        status = "PASS" if ok else "FAIL"
    print("[%s] %-16s %s" % (status, key, desc))
    if verdict and verdict != status:
        print("       -> %s" % verdict)
    if not ok:
        tail = [l for l in out.strip().splitlines() if l.strip()][-6:]
        for line in tail:
            print("       | " + line)
    results.append((key, status, desc))

print("=" * 74)
passed = sum(1 for _, s, _ in results if s == "PASS")
failed = [k for k, s, _ in results if s == "FAIL"]
skipped = [k for k, s, _ in results if s == "SKIP"]
pending = [k for k, s, _ in results if s == "PEND"]
print("passed %d, failed %d, skipped %d, pending %d of %d"
      % (passed, len(failed), len(skipped), len(pending), len(results)))
if pending:
    print("pending: %s" % ", ".join(pending))
    print("  (the hardware supports these; board access is what is missing)")
if failed:
    print("failed: %s" % ", ".join(failed))
if skipped:
    print("skipped (need Vivado): %s" % ", ".join(skipped))
print("SUITE-PASS" if not failed else "SUITE-FAIL")
sys.exit(0 if not failed else 1)
