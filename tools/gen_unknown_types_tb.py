"""Generate tb_unknown_types.v against itch_parse's actual port list.

My first attempt guessed the interface and got it wrong (64-bit tdata, evt/evt_valid
rather than m_evt_*, and s_axi_awprot/s_axi_arprot exist). Rather than hand-correct a
long port list, this builds the instantiation from the module declaration, so a
future interface change surfaces as a generated-code diff instead of a mystery
compile error.

The test itself answers one question: does an unknown ITCH message type (one that
falls into `default: len_ok_next = 1'b1`) desynchronise the parser?

The claim being checked is that it cannot, because MoldUDP64 gives every message its
own 2-byte length prefix - the declared length IS the framing. If that holds, a
capture full of types the parser does not decode still parses exactly. If it does
not hold, real captures would corrupt quietly and no existing suite would notice,
because they all use the same well-formed file.
"""
import io
import re

RTL = r"D:\agent\nasdaq-fpga\rtl\itch\itch_parse.v"
OUT = r"D:\agent\nasdaq-fpga\tools\tb_unknown_types.v"

src = io.open(RTL, encoding="utf-8", errors="replace").read()

# Extract the port list.
m = re.search(r"module itch_parse\s*\((.*?)\n\);", src, re.S)
assert m, "module declaration not found"
body = m.group(1)

ports = []
for pm in re.finditer(
        r"(input|output)\s+wire\s*(\[[^\]]+\])?\s*(\w+)", body):
    direction = pm.group(1)
    width = pm.group(2) or ""
    name = pm.group(3)
    ports.append((direction, width.strip(), name))

print("ports found: %d" % len(ports))

# Declarations for the testbench.
decls = []
conns = []
# aclk and aresetn are GENERATED by the testbench, so they must not be declared
# again here - that produced "second declaration of 'aclk' is ignored".
TB_OWNED = {"aclk", "aresetn"}
for direction, width, name in ports:
    if name in TB_OWNED:
        conns.append("        .%s (%s)" % (name, name))
        continue
    if direction == "input":
        if width:
            decls.append("    reg  %s %s = 0;" % (width, name))
        else:
            decls.append("    reg  %s = 0;" % name)
    else:
        if width:
            decls.append("    wire %s %s;" % (width, name))
        else:
            decls.append("    wire %s;" % name)
    conns.append("        .%s (%s)" % (name, name))

# Ready/valid inputs that must be driven high for the parser to make progress.
FIXED = {
    "s_axi_bready": "1",
    "s_axi_rready": "1",
    # evt_ready must be high or msg_latched never clears and TREADY never rises
    # again: the parser accepts exactly one message and then stalls forever.
    "evt_ready": "1",
}

extra = []
for direction, width, name in ports:
    if direction == "input" and name in FIXED:
        extra.append("    initial %s = %s;" % (name, FIXED[name]))

TEMPLATE = r"""// Does an unknown ITCH message type desynchronise the parser?
//
// itch_parse validates the 2-byte length prefix only for the eight types it
// decodes; everything else takes `default: len_ok_next = 1'b1`.
//
// The claim: because MoldUDP64 gives every message its own 2-byte length prefix,
// the declared length IS the framing, so an undecoded type cannot desynchronise
// the stream. If that is false, a real capture corrupts quietly - and no existing
// suite would catch it, because they all stream the same well-formed file.
//
// This streams decodable ADDs interleaved with unknown types of odd lengths (1, 3
// and 7 bytes). If the parser stays in step, every ADD is decoded.
//
// The port list below was generated from the module declaration by
// tools/gen_unknown_types_tb.py, not typed by hand.

`timescale 1ns / 1ps

module tb_unknown_types;

    reg         aclk = 0;
    reg         aresetn = 0;
    always #3.0 aclk = ~aclk;

@@DECLS@@

    itch_parse dut (
@@CONNS@@
    );

@@EXTRA@@

    localparam integer NADDS = 8;
    localparam integer MAXB  = 2048;
    reg [7:0] pkt [0:MAXB-1];
    reg       msg_end [0:MAXB-1];
    integer nbytes = 0;
    integer i, j;
    integer evts = 0;

    task push(input [7:0] b);
        begin
            pkt[nbytes] = b;
            nbytes = nbytes + 1;
        end
    endtask

    task push_len(input [15:0] l);
        begin
            push(l[15:8]);
            push(l[7:0]);
        end
    endtask

    // Count decoded events as they appear.
    always @(posedge aclk) begin
        if (aresetn && evt_valid && evt_ready)
            evts <= evts + 1;
    end

    initial begin
        for (i = 0; i < NADDS; i = i + 1) begin
            // unknown type, 1-byte body: 'E' Execution is not decoded
            push_len(16'd1); push(8'h45);
            // unknown, 3-byte body: 'C' Cross Trade
            push_len(16'd3); push(8'h43); push(8'h00); push(8'h11);
            // unknown, 7-byte body: 'B' Broken Trade
            push_len(16'd7); push(8'h42);
            for (j = 0; j < 6; j = j + 1) push(8'h00);
            // a decodable ADD, 36 bytes, stock_locate 6836
            push_len(16'd36);
            push(8'h41);                 // 'A'
            push(8'h1A); push(8'hB4);    // stock_locate = 6836
            push(8'h00); push(8'h00);    // tracking
            push(8'h00); push(8'h00);
            push(8'h00); push(8'h00);
            push(8'h00); push(8'h00);
            push(8'h00); push(8'h00);    // timestamp (6)
            for (j = 0; j < 8; j = j + 1) push(8'h00);   // order ref
            push(8'h42);                 // buy
            for (j = 0; j < 4; j = j + 1) push(8'h00);   // shares
            for (j = 0; j < 8; j = j + 1) push(8'h00);   // stock
            for (j = 0; j < 4; j = j + 1) push(8'h00);   // price
        end

        // Mark the last byte of each message for TLAST.
        // The whole array must be cleared first: an uninitialised entry holds X,
        // TLAST becomes X, and the parser's msg_latched logic stalls on it.
        for (i = 0; i < MAXB; i = i + 1) msg_end[i] = 1'b0;
        begin : mark
            integer p2; integer q2; integer ln2;
            p2 = 0;
            while (p2 < nbytes) begin
                ln2 = (pkt[p2] << 8) | pkt[p2+1];
                q2 = p2 + 2 + ln2 - 1;
                msg_end[q2] = 1'b1;
                p2 = p2 + 2 + ln2;
            end
        end
        $display("stream: %0d bytes, %0d ADDs interleaved with unknown types",
                 nbytes, NADDS);

        aresetn = 0;
        repeat (20) @(posedge aclk);
        aresetn = 1;
        repeat (10) @(posedge aclk);

        // enable
        @(negedge aclk);
        s_axi_awaddr = 5'h14; s_axi_awvalid = 1;
        s_axi_wdata  = 32'h1; s_axi_wstrb = 4'hF; s_axi_wvalid = 1;
        @(posedge aclk);
        while (!(s_axi_awready && s_axi_wready)) @(posedge aclk);
        @(negedge aclk);
        s_axi_awvalid = 0; s_axi_wvalid = 0;

        // one byte per beat, TLAST on the last byte of each message is not
        // required by this parser; it frames on the length prefix.
        // TLAST marks the final byte of each MESSAGE (the parser frames on the
        // length prefix, but tb_book and the real chain assert TLAST per message,
        // and itch_parse's msg_latched logic expects it).
        for (i = 0; i < nbytes; i = i + 1) begin
            @(negedge aclk);
            s_axis_tdata  = {56'd0, pkt[i]};
            s_axis_tkeep  = 8'h01;
            s_axis_tlast  = msg_end[i];
            s_axis_tvalid = 1'b1;
            @(posedge aclk);
            while (!s_axis_tready) @(posedge aclk);
        end
        @(negedge aclk);
        s_axis_tvalid = 0;
        s_axis_tkeep  = 8'h00;
        s_axis_tlast  = 0;

        repeat (600) @(posedge aclk);

        $display("UNKNOWN parsed=%0d events=%0d expected=%0d",
                 dut.parse_cnt, evts, NADDS);
        // The parser must stay in step: every ADD decoded, none lost.
        if (dut.parse_cnt == NADDS && evts == NADDS)
            $display("UNKNOWN-PASS");
        else
            $display("UNKNOWN-FAIL");
        $finish;
    end

endmodule
"""

out = (TEMPLATE.replace("@@DECLS@@", "\n".join(decls))
              .replace("@@CONNS@@", ",\n".join(conns))
              .replace("@@EXTRA@@", "\n".join(extra)))
io.open(OUT, "w", encoding="utf-8", newline="\n").write(out)
print("wrote %s" % OUT)
