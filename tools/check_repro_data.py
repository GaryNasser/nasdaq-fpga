"""Do the documented reproduction commands produce the files the tests open?

Round 68 found section 9.2's command list generated `itch_1m.mold64` but never
`itch_loc6836.mold64` - the file tb_realfile, tb_rate_book and the driver's golden run all
read. Following the instructions exactly left the reader unable to run any board test.

The general form of that fault: a documented pipeline whose OUTPUTS do not cover the
inputs the code requires. It is checkable without running anything - compare the two sets:

    produced  = every --output argument in the doc's command block
    consumed  = every data/ path opened by tools/ and rtl/ testbenches

Anything consumed and not produced is an undocumented prerequisite.

Caveat: some consumed files are legitimately obtained elsewhere (the board's copy of the
capture is deployed, not built). Those are listed in EXEMPT with the reason, so the
exemption is visible rather than silently forgiven.
"""
import glob
import io
import os
import re
import sys

REPO = r"D:\agent\nasdaq-fpga"
REPORT = os.path.join(REPO, "docs", "final-report.md")

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

text = io.open(REPORT, encoding="utf-8", errors="surrogateescape").read()

# --- produced: --output arguments in the repro section ----------------------
i = text.find("### 9.2 数据")
if i == -1:
    print("REPRO-DATA-FAIL (section 9.2 not found)")
    sys.exit(1)
j = text.find("\n### ", i + 5)
section = text[i:j if j != -1 else len(text)]

produced = set()
for m in re.finditer(r"--output\s+(\S+\.(?:raw|mold64))", section):
    produced.add(os.path.basename(m.group(1)))

# Also tools invoked in the section that emit derived files.
derived = set()
for m in re.finditer(r"python\s+(tools/\w+\.py)", section):
    derived.add(os.path.basename(m.group(1)))

print("data files the documented commands produce")
print()
for p in sorted(produced):
    print("  %s" % p)
print()
print("  helper scripts invoked: %s" % (", ".join(sorted(derived)) or "none"))

# --- consumed: data/ paths opened by tools and testbenches ------------------
consumed = set()
for pattern in ("tools/*.py", "tools/*.v", "board/*.py"):
    for path in glob.glob(os.path.join(REPO, pattern)):
        src = io.open(path, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r"data[\\/]([\w.\-]+\.(?:raw|mold64|hex|jsonl))", src):
            consumed.add(m.group(1))

print()
print("data files the code opens")
print()
for c in sorted(consumed):
    print("  %s" % c)

# Files fetched at run time or deployed rather than built.
EXEMPT = {
    "itch_1m.raw.manifest.json": "written by fetch_itch.py as a sidecar",
    "itch_test_synthetic.raw": "generated by a testbench helper",
    "events_test.jsonl": "committed test fixture (small)",
    "test_3pkt.mold64": "committed fixture (small)",
}

missing = []
for c in sorted(consumed):
    if c in produced or c in EXEMPT:
        continue
    # Files produced by the helper scripts we saw.
    if c.startswith("nasdaq_rf") or c.endswith(".hex"):
        continue
    missing.append(c)

print()
print("  consumed but not produced by the documented commands: %d" % len(missing))
for m in missing:
    print("     %s" % m)

print()
if missing:
    print("REPRO-DATA-FAIL (%d)" % len(missing))
    for m in missing:
        print("  %s is read by the code but no documented command creates it" % m)
    sys.exit(1)
if not produced:
    print("REPRO-DATA-FAIL (no outputs parsed - the comparison would be vacuous)")
    sys.exit(1)
print("REPRO-DATA-PASS (every data file the code opens is documented)")
