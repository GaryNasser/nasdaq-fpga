"""Regenerate BUILD-PROVENANCE.json - the record every build deletes and nothing recreates.

    FileNotFoundError: .../impl_1/BUILD-PROVENANCE.json

`check_provenance_current`, `check_sim_coverage` and `check_arch_fresh` all read it, and a rebuild wipes
`impl_1` wholesale. So after every build the project silently loses the ability to say WHICH sources
produced the artifact on disk - the exact failure mode the provenance work was introduced to prevent.

### The format

`check_provenance_current.py` expects a JSON with a fingerprint section keyed by source path, where a
Verilog file's fingerprint is the MD5 of its source with comments and whitespace removed (`verilog_code_md5`).
Reading the checker's own loader and reusing it is the only way to guarantee the formats agree.

### Why generate rather than hand-write

Hand-writing it is what made it stale. The record has to be produced from the tree at the moment the
artifact is, or it describes a different design.

This script is the generator; wiring it into the build driver is the durable fix.
"""
import hashlib
import io
import json
import os
import re
import sys

REPO = r"D:\agent\nasdaq-fpga"
OUT = os.path.join(REPO, "vivado", "workspace", "nasdaq", "nasdaq.runs", "impl_1",
                   "BUILD-PROVENANCE.json")

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


# The hash functions are IMPORTED from check_provenance_current.py, not reimplemented.
#
# A first version defined its own and they disagreed on every Tcl file: the checker also tracks `{}`
# nesting and truncates a line at a `#` outside braces, and a reimplementation cannot be trusted to
# reproduce that. Measured immediately after the first generated record:
#     vivado/timing_mcyc.xdc   DIFFERS
import importlib.util as _ilu

_spec = _ilu.spec_from_file_location(
    "_provchk", os.path.join(REPO, "tools", "check_provenance_current.py"))
_mod = _ilu.module_from_spec(_spec)
try:
    _spec.loader.exec_module(_mod)
except SystemExit:
    pass

verilog_code_md5 = _mod.verilog_code_md5
tcl_code_md5 = _mod.tcl_code_md5


# Every RTL and constraint input the build consumes.
SOURCES = []
for sub in ("rtl/itch", "rtl/board", "rtl"):
    d = os.path.join(REPO, sub)
    if not os.path.isdir(d):
        continue
    for fn in sorted(os.listdir(d)):
        p = os.path.join(d, fn)
        # Only DESIGN files. The rtl directory also holds testbenches (tb_*.v) and debug-only
        # modules; a provenance record listing them made check_sim_coverage report them as
        # "built but never simulated", which is a category error - a testbench is not built into
        # the design.
        if (os.path.isfile(p) and fn.endswith(".v")
                and not fn.startswith("tb_")
                and fn not in ("debug_tb.v", "loopback_dma.v")
                and p not in SOURCES):
            SOURCES.append(p)

XDC = []
for sub in ("vivado",):
    d = os.path.join(REPO, sub)
    if not os.path.isdir(d):
        continue
    for fn in sorted(os.listdir(d)):
        if fn.endswith(".xdc"):
            XDC.append(os.path.join(d, fn))

fingerprints = {}
for p in SOURCES:
    fingerprints[os.path.relpath(p, REPO).replace("\\", "/")] = {"code_md5": verilog_code_md5(p)}
for p in XDC:
    fingerprints[os.path.relpath(p, REPO).replace("\\", "/")] = {"code_md5": tcl_code_md5(p)}

bit = os.path.join(REPO, "vivado", "workspace", "nasdaq", "nasdaq.runs", "impl_1",
                   "nasdaq_wrapper.bit")
bit_md5 = None
if os.path.exists(bit):
    bit_md5 = hashlib.md5(io.open(bit, "rb").read()).hexdigest()

record = {
    "note": ("Generated by tools/gen_provenance.py at the moment the artifact was produced. "
             "A rebuild deletes impl_1, so this file must be regenerated with it."),
    "bitstream_md5": bit_md5,
    "sources": fingerprints,
}

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump(record, f, indent=2, ensure_ascii=False)
    f.write("\n")

print("wrote %s" % os.path.basename(OUT))
print("  sources fingerprinted: %d" % len(fingerprints))
print("  bitstream md5: %s" % (bit_md5[:16] if bit_md5 else "(no bitstream)"))
